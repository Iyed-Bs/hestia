export const dictionaries: Record<Lang, Record<Key, string>> = { en, fr };

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key) => string;
  fmt: (value: number | null | undefined, digits?: number) => string;
}

const I18nContext = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("hestia.lang");
    if (saved === "en" || saved === "fr") return saved;
  } catch {
    /* storage blocked: fall through */
  }
  return navigator.language.startsWith("fr") ? "fr" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    document.documentElement.lang = next;
    try {
      localStorage.setItem("hestia.lang", next);
    } catch {
      /* ignore */
    }
  }, []);
  const value = useMemo<I18n>(() => {
    const number = (digits: number) =>
      new Intl.NumberFormat(lang === "fr" ? "fr-FR" : "en-GB", { maximumFractionDigits: digits, minimumFractionDigits: digits });
    return {
      lang,
      setLang,
      t: (key) => dictionaries[lang][key] ?? en[key] ?? key,
      fmt: (value, digits = 0) => (value === null || value === undefined || Number.isNaN(value) ? "—" : number(digits).format(value)),
    };
  }, [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
